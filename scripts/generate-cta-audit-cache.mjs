#!/usr/bin/env node
/**
 * scripts/generate-cta-audit-cache.mjs
 *
 * verified CTA の最終遷移先を全件ネットワーク検証し、
 * data/cta-audit-cache.json へ証跡を書き出す。
 *
 * これは「strict」モードの実行で、ALLOW_NETWORK_SKIP を一切考慮しない。
 * CI の verify:lint（ALLOW_NETWORK_SKIP=1）はこの証跡を消費して
 * coverage を満たす。scheduled workflow が週1で本スクリプトを実行し、
 * 証跡をリポジトリへコミットする。
 *
 * 使い方:
 *   node scripts/generate-cta-audit-cache.mjs
 */

import fs from "node:fs";
import path from "node:path";
import {
  collectVerifiedCtaUrls,
  outboundHostAllowlist,
  auditVerifiedCtaDestinations,
  CTA_CACHE_FILE,
} from "./check-purchase-link-consistency.mjs";

const CACHE_PATH = path.resolve(CTA_CACHE_FILE);

async function main() {
  console.log("Generating CTA audit cache (strict mode, no network skip)...");

  const { ctas, statuses } = collectVerifiedCtaUrls();
  const verifiedSlugs = [...statuses.entries()]
    .filter(([, status]) => status === "verified")
    .map(([slug]) => slug);

  console.log(
    `Found ${ctas.length} CTAs from ${verifiedSlugs.length} verified articles`,
  );

  const allowlist = outboundHostAllowlist();
  const audit = await auditVerifiedCtaDestinations({
    urls: ctas,
    allowlist,
    allowNetworkSkip: false,
  });

  for (const warning of audit.warnings) console.warn(warning);

  const resolved = audit.checked.filter((e) => e.result === "resolved");
  const skipped = audit.checked.filter((e) => e.result === "skipped");

  console.log(
    `Audit complete: ${resolved.length} resolved, ${skipped.length} skipped, ${audit.errors.length} errors`,
  );

  if (audit.errors.length) {
    console.error("Errors:");
    for (const err of audit.errors) console.error(`  ${err}`);
    console.error(
      "\nFix the errors above before generating the cache. The cache should only contain verified evidence.",
    );
    process.exit(1);
  }

  // Build cache entries from resolved CTAs
  const entries = resolved.map((entry) => ({
    article: entry.article,
    url: entry.url,
    finalUrl: entry.finalUrl,
    finalHost: entry.finalHost,
    hops: entry.hops,
    checkedAt: new Date().toISOString(),
  }));

  const cache = {
    schemaVersion: 1,
    generatedAt: new Date().toISOString(),
    description:
      "Verified CTA destination audit evidence. Generated by scripts/generate-cta-audit-cache.mjs. CI verify:lint (ALLOW_NETWORK_SKIP=1) uses this to prove coverage when network calls are skipped.",
    entries,
  };

  // Ensure data/ directory exists
  const dataDir = path.dirname(CACHE_PATH);
  if (!fs.existsSync(dataDir)) {
    fs.mkdirSync(dataDir, { recursive: true });
  }

  fs.writeFileSync(CACHE_PATH, JSON.stringify(cache, null, 2) + "\n");
  console.log(`Cache written to ${CACHE_PATH} (${entries.length} entries)`);
}

main();
